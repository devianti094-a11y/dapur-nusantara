class MenuItem {
  final String id;
  final String name;
  final String description;
  final int price;
  final String category;
  final String image;
  final double rating;

  MenuItem({
    required this.id,
    required this.name,
    required this.description,
    required this.price,
    required this.category,
    required this.image,
    required this.rating,
  });
}